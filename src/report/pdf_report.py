# Verdict palette mirrors the web headline card so print and screen agree.
_VERDICT_COLORS: dict[str, tuple[str, str]] = {
    "Normal ECG": ("#166534", "#F0FDF4"),
    "Abnormal ECG": ("#991B1B", "#FEF2F2"),
    "Indeterminate ECG": ("#92400E", "#FFFBEB"),
}
_DEFAULT_VERDICT_COLOR: tuple[str, str] = ("#1E3A8A", "#F8FAFC")

# reportlab's built-in Helvetica lacks Turkish glyphs (ş, ı, ğ, İ render as
# boxes), which breaks the Turkish AI summary. DejaVu Sans (shipped with
# matplotlib, already a dependency) has full Turkish coverage. Register it once
# and use it everywhere; fall back to Helvetica if registration fails (English
# still renders fine).
_FONT_REGULAR = "Helvetica"
_FONT_BOLD = "Helvetica-Bold"


def _register_unicode_fonts() -> None:
    global _FONT_REGULAR, _FONT_BOLD
    if _FONT_REGULAR == "CorioSans":  # already registered
        return
    try:
        import matplotlib

        ttf_dir = Path(matplotlib.__file__).parent / "mpl-data" / "fonts" / "ttf"
        pdfmetrics.registerFont(TTFont("CorioSans", str(ttf_dir / "DejaVuSans.ttf")))
        pdfmetrics.registerFont(
            TTFont("CorioSans-Bold", str(ttf_dir / "DejaVuSans-Bold.ttf"))
        )
        # Map the family so inline <b> tags in Paragraphs use the bold TTF
        # (otherwise <b> falls back to Helvetica-Bold and Turkish breaks again).
        pdfmetrics.registerFontFamily(
            "CorioSans", normal="CorioSans", bold="CorioSans-Bold"
        )
        _FONT_REGULAR = "CorioSans"
        _FONT_BOLD = "CorioSans-Bold"
    except Exception:  # noqa: BLE001 — fall back to Helvetica (Latin-only)
        pass


_DISCLAIMER: str = (
    "<b>Disclaimer:</b> This report is generated by an experimental AI pipeline "
    "for research and educational purposes only. It is NOT a medical device and "
    "must NOT be used for clinical decision-making. Final responsibility for any "
    "interpretation rests with a qualified reviewing clinician."
)


