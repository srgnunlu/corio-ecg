# Professional PDF report generation (Phase D.2).
#
# Renders a structured ECGReport (HR, rhythm, intervals, AI diagnoses) plus the
# original photo and the digitized 12-lead tracing into a single A4 PDF using
# reportlab. This layer NEVER computes clinical findings; it only typesets what
# the deterministic + model pipeline already produced. A disclaimer on every
# page makes the research/decision-support framing explicit.

